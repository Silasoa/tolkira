import { stripBidiControls } from '../text.js';

export function escapeHtml(value: unknown): string {
  return stripBidiControls(String(value ?? '')).replace(/[&<>"']/g, (character) => {
    switch (character) {
      case '&':
        return '&amp;';
      case '<':
        return '&lt;';
      case '>':
        return '&gt;';
      case '"':
        return '&quot;';
      case "'":
        return '&#39;';
      default:
        return character;
    }
  });
}
