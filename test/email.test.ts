describe('renderEmail failed list', () => {
  it('lists at most five failed scenarios and counts the rest', () => {
    const scenarios = Array.from({ length: 6 }, (_, index) => {
      const number = index + 1;
      return buildScenario({
        name: `Failure ${String(number).padStart(2, '0')}`,
        feature: `Feature ${String(number).padStart(2, '0')}`,
        status: 'failed',
        durationMs: number * 1000,
        steps: [
          {
            keyword: 'Then',
            text: `TOP SECRET STEP BODY ${number}`,
            status: 'failed',
            durationMs: number * 1000,
          },
        ],
      });
    });
    const summary = buildSummary({
      status: 'failed',
      counts: {
        features: 6,
        scenarios: statusCounts({ failed: 6 }),
        steps: statusCounts({ failed: 6 }),
      },
      scenarios,
    });
    const html = render(summary, { title: TITLE });
    const text = plainText(html);

    const shown = scenarios.filter((scenario) => text.includes(scenario.name));
    expect(shown).toHaveLength(5);

    for (const scenario of shown) {
      expect(text).toContain(scenario.feature);
      expect(text, `${scenario.name} duration`).toContain(
        `${scenario.durationMs / 1000} s`,
      );
      expect(text, `${scenario.name} status`).toContain('Failed ·');
    }

    expect(text).toMatch(/1 more failed scenario/i);
    expect(text).not.toContain('TOP SECRET STEP');
    expect(html).not.toContain('TOP SECRET STEP');
  });

  it('does not call a non-passing run successful', () => {
    const cases: Array<{ status: SummaryStatus; label: string }> = [
      { status: 'pending', label: 'Pending' },
      { status: 'undefined', label: 'Undefined' },
      { status: 'unknown', label: 'Unknown' },
    ];

    for (const entry of cases) {
      const summary = buildSummary({
        status: entry.status,
        counts: {
          features: 1,
          scenarios: statusCounts({ [entry.status]: 1 }),
          steps: statusCounts(),
        },
        scenarios: [
          buildScenario({ name: 'Needs attention', status: entry.status }),
        ],
      });
      const text = plainText(render(summary, { title: TITLE }));

      expect(text, entry.status).toContain('No failed scenarios');
      expect(text, entry.status).toContain('Run status');
      expect(text, entry.status).toContain(entry.label);
      expect(text, entry.status).not.toMatch(/\bsuccessful\b/i);
      expect(text, entry.status).not.toMatch(/\ball passed\b/i);
    }
  });

  it('shows the plain no-failure copy for a passed run', () => {
    const summary = buildSummary({
      status: 'passed',
      counts: {
        features: 1,
        scenarios: statusCounts({ passed: 2 }),
        steps: statusCounts({ passed: 4 }),
      },
      scenarios: [
        buildScenario({ name: 'Green one', status: 'passed' }),
        buildScenario({ name: 'Green two', status: 'passed' }),
      ],
    });
    const text = plainText(render(summary, { title: TITLE }));

    expect(text).toContain('No failed scenarios.');
    expect(text).not.toContain('Run status');
  });
});

describe('renderEmail escaping and report note', () => {
  it('shows hostile feature and scenario names literally, never as markup', () => {
    const feature = 'Kontoeröffnung <img src=x onerror="alert(1)"> & "Zitat"';
    const scenarioName = '"><script>alert(2)</script>';
    const summary = buildSummary({
      status: 'failed',
      counts: {
        features: 1,
        scenarios: statusCounts({ failed: 1 }),
        steps: statusCounts({ failed: 1 }),
      },
      scenarios: [
        buildScenario({ name: scenarioName, feature, status: 'failed' }),
      ],
    });
    const html = render(summary, {
      title: '<b>Bold</b> & "quoted"',
      reportName: '../../<script>alert(9)</script>.html',
    });
    const text = plainText(html);

    expect(html).not.toMatch(/<img\b/i);
    expect(html).not.toMatch(/<script\b/i);
    expect(html).not.toMatch(/<b\b/i);
    expect(html).not.toMatch(/<[^>]*\sonerror\s*=/i);
    expect(html).toContain('&lt;img');
    expect(html).toContain('&lt;script');

    expect(text).toContain(feature);
    expect(text).toContain(scenarioName);
    expect(heading(html)).toBe('<b>Bold</b> & "quoted" — Failed');
    expect(text).toContain('script>.html');
    expect(text).not.toContain('../../');
  });

  it('names only the report basename and says to attach or share it', () => {
    const text = plainText(
      render(
        buildSummary({
          status: 'failed',
          counts: {
            features: 1,
            scenarios: statusCounts({ failed: 1 }),
            steps: statusCounts({ failed: 1 }),
          },
          scenarios: [buildScenario({ name: 'Broken', status: 'failed' })],
        }),
        { title: TITLE, reportName: 'reports/nested/run.html' },
      ),
    );

    expect(text).toContain('run.html');
    expect(text).not.toContain('reports/nested');
    expect(text).toMatch(/attach or share/i);
  });

  it('tells the recipient that no full report is attached', () => {
    const text = plainText(
      render(
        buildSummary({
          status: 'failed',
          counts: {
            features: 1,
            scenarios: statusCounts({ failed: 1 }),
            steps: statusCounts({ failed: 1 }),
          },
          scenarios: [buildScenario({ name: 'Broken', status: 'failed' })],
        }),
        { title: TITLE },
      ),
    );

    expect(text).toContain('No full report is attached.');
    expect(text).not.toContain('--out');
    expect(text).not.toContain('Full report:');
  });
});
