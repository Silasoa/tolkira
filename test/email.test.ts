const NOW = new Date('2026-11-20T09:30:00.000Z');
const TITLE = 'Nightly run';

function statusCounts(
  values: Partial<Omit<StatusCounts, 'total'>> = {},
): StatusCounts {
  const merged = {
    passed: 0,
    failed: 0,
    skipped: 0,
    pending: 0,
    undefined: 0,
    ambiguous: 0,
    unknown: 0,
    ...values,
  };
  return {
    total:
      merged.passed +
      merged.failed +
      merged.skipped +
      merged.pending +
      merged.undefined +
      merged.ambiguous +
      merged.unknown,
    ...merged,
  };
}

function buildSummary(partial: Partial<ReportSummary> = {}): ReportSummary {
  return {
    schemaVersion: SUMMARY_SCHEMA_VERSION,
    status: 'failed',
    durationMs: 0,
    counts: {
      features: 0,
      scenarios: statusCounts(),
      steps: statusCounts(),
    },
    attachments: { total: 0, bytes: 0 },
    scenarios: [],
    ...partial,
  };
}

let scenarioNumber = 0;

function buildScenario(input: {
  name: string;
  feature?: string;
  status?: SummaryStatus;
  uri?: string;
  executed?: boolean;
  durationMs?: number;
  steps?: SummaryStep[];
}): SummaryScenario {
  scenarioNumber += 1;
  return {
    name: input.name,
    uri: input.uri ?? `features/scenario-${scenarioNumber}.feature`,
    feature: input.feature ?? 'Checkout',
    status: input.status ?? 'failed',
    executed: input.executed ?? true,
    durationMs: input.durationMs ?? 0,
    attempt: 0,
    tags: [],
    attachments: 0,
    steps: input.steps ?? [],
  };
}

function render(summary: ReportSummary, options: EmailOptions = {}): string {
  return renderEmail(summary, { now: NOW, ...options });
}

function flat(value: string): string {
  return value.replaceAll(/\s+/g, ' ').trim();
}

function plainText(html: string): string {
  return flat(
    html
      .replaceAll(/<style\b[\s\S]*?<\/style>/gi, ' ')
      .replaceAll(/<[^>]*>/g, ' ')
      .replaceAll('&lt;', '<')
      .replaceAll('&gt;', '>')
      .replaceAll('&quot;', '"')
      .replaceAll('&#39;', "'")
      .replaceAll('&middot;', '·')
      .replaceAll('&amp;', '&'),
  );
}

function heading(html: string): string {
  const match = /<h1\b[^>]*>([\s\S]*?)<\/h1>/i.exec(html);
  if (!match) return '';
  return plainText(match[1] as string);
}

function escapeRegExp(value: string): string {
  return value.replaceAll(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

/** Accepts "3 features" and "Features: 3" so the template stays free. */
function hasMetric(
  text: string,
  label: string,
  value: string | number,
): boolean {
  const v = escapeRegExp(String(value));
  return new RegExp(`(?:${v}\\s+${label}|${label}\\s*:?\\s*${v})`, 'i').test(
    text,
  );
}

function hasStatusCount(text: string, label: string, count: number): boolean {
  return hasMetric(text, escapeRegExp(label), count);
}

