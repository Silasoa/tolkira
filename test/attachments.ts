export async function writeAttachmentReport(
  dir: string,
  attachments: unknown[],
  name = 'playwright.json',
  specTitle = 'attachment test',
): Promise<string> {
  const file = path.join(dir, name);
  await writeFile(
    file,
    `${JSON.stringify(attachmentReport(attachments, specTitle), null, 2)}\n`,
    'utf8',
  );
  return file;
}

export function attachmentTexts(envelopes: Envelope[]): string[] {
  return envelopes
    .flatMap((envelope) => (envelope.attachment ? [envelope.attachment] : []))
    .map((attachment) => Buffer.from(attachment.body, 'base64').toString('utf8'));
}
